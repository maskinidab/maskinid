create or replace function public.get_share_view(p_token text, p_ip_hash text default null)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare s public.share_links; m public.machines;
begin
  if p_ip_hash is not null and not app.rate_limit_hit('share:' || p_ip_hash, 60, interval '1 minute') then perform app.raise('RATE_LIMITED'); end if;
  select * into s from public.share_links where token_hash = app.sha256_hex(coalesce(p_token, '')) for update;
  if s.id is null then return jsonb_build_object('ok', false, 'reason', 'not_found'); end if;
  if s.revoked_at is not null then return jsonb_build_object('ok', false, 'reason', 'revoked'); end if;
  if s.expires_at <= now() then return jsonb_build_object('ok', false, 'reason', 'expired'); end if;
  if s.max_views is not null and s.views >= s.max_views then return jsonb_build_object('ok', false, 'reason', 'max_views'); end if;
  update public.share_links set views = views + 1 where id = s.id;
  if s.machine_id is not null then
    select * into m from public.machines where id = s.machine_id;
    insert into public.access_log (machine_id, viewer_type, via, ip_hash, visible_to_owner) values (m.id, 'public', 'share_link', p_ip_hash, true);
  end if;
  return jsonb_build_object('ok', true, 'scope', s.scope, 'expires_at', s.expires_at,
    'views_left', case when s.max_views is null then null else s.max_views - s.views - 1 end,
    'shared_by', (select name from public.organizations where id = s.org_id),
    'data', case s.scope
      when 'public_card' then app.public_card_json(m, null)
      when 'buyer_report' then app.buyer_report(m.id)
      else app.shared_fleet_view(s) end);
end $$;


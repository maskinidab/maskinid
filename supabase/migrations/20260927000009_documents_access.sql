-- ---------- Rate limiting (SPEC §11.3: 30/min, 300/day per IP on public lookups) ----------
create table app.rate_limits (
  key          text not null,
  window_start timestamptz not null,
  hits         int not null default 0,
  primary key (key, window_start)
);
revoke all on app.rate_limits from public, anon, authenticated, service_role;

-- Counts a hit; returns false when the limit for the window is exceeded.
create or replace function app.rate_limit_hit(p_key text, p_limit int, p_window interval)
returns boolean language plpgsql security definer set search_path = '' as $$
declare ws timestamptz := to_timestamp(floor(extract(epoch from now()) / extract(epoch from p_window)) * extract(epoch from p_window));
  n int;
begin
  insert into app.rate_limits (key, window_start, hits) values (p_key, ws, 1)
  on conflict (key, window_start) do update set hits = app.rate_limits.hits + 1
  returning hits into n;
  return n <= p_limit;
end $$;

-- ---------- Access logging ----------
create or replace function app.viewer_type_for(p_org_id uuid)
returns public.viewer_type language sql stable security definer set search_path = '' as $$
  select case
    when p_org_id is null then 'public'
    when app.is_operator() then 'operator'
    when app.has_org_type(p_org_id, 'authority') then 'authority'
    when app.has_org_type(p_org_id, 'financier') then 'financier'
    when app.has_org_type(p_org_id, 'insurer') then 'insurer'
    when app.has_org_type(p_org_id, 'inspector') then 'inspector'
    when app.has_org_type(p_org_id, 'dealer') then 'dealer'
    when app.has_org_type(p_org_id, 'marketplace') then 'marketplace'
    when app.has_org_type(p_org_id, 'manufacturer') then 'manufacturer'
    when app.has_org_type(p_org_id, 'client') then 'client'
    else 'owner' end::public.viewer_type
$$;

-- Logs every read of another organisation's machine (SPEC §0 principle 3). Authority reads are hidden from the owner
-- unless the authority org's setting show_authority_reads_to_owner is true; operator reads are never shown.
create or replace function app.after_lookup(p_org_id uuid, p_machine_ids uuid[], p_via text)
returns void language plpgsql security definer set search_path = '' as $$
declare mid uuid; m public.machines; vt public.viewer_type; visible boolean;
begin
  vt := case when app.current_api_key_id() is not null then 'api' else app.viewer_type_for(p_org_id) end;
  visible := case
    when vt = 'operator' then false
    when vt = 'authority' then coalesce((select (settings ->> 'show_authority_reads_to_owner')::boolean from public.organizations where id = p_org_id), false)
    else true end;
  foreach mid in array coalesce(p_machine_ids, '{}') loop
    select * into m from public.machines where id = mid;
    if m.id is null or m.owner_org_id = p_org_id or m.user_org_id = p_org_id then continue; end if;
    -- One row per viewer org and machine per hour for plain web views, every row for checks and scans.
    if p_via = 'web' and exists (select 1 from public.access_log a where a.machine_id = mid and a.viewer_org_id is not distinct from p_org_id
        and a.viewer_user_id is not distinct from auth.uid() and a.via = 'web' and a.created_at > now() - interval '1 hour') then
      continue;
    end if;
    insert into public.access_log (machine_id, viewer_user_id, viewer_org_id, viewer_type, via, visible_to_owner)
    values (mid, auth.uid(), p_org_id, vt, p_via::public.access_via, visible);
  end loop;
end $$;

-- Public scan through Edge Function scan-log (service role): rate limit, card, access log, stolen-machine alerts.
create or replace function public.log_public_scan(p_code text, p_reg text, p_ip_hash text, p_user_agent_family text default null,
  p_location jsonb default null)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare card jsonb; m public.machines; loc jsonb; ev public.events;
begin
  if not app.rate_limit_hit('scan:min:' || coalesce(p_ip_hash, 'none'), app.config_text('PUBLIC_RATE_PER_MIN', '30')::int, interval '1 minute')
     or not app.rate_limit_hit('scan:day:' || coalesce(p_ip_hash, 'none'), app.config_text('PUBLIC_RATE_PER_DAY', '300')::int, interval '1 day') then
    perform app.raise('RATE_LIMITED');
  end if;
  card := public.public_machine_card(p_code, p_reg);
  if not (card ->> 'found')::boolean then return card; end if;
  select * into m from public.machines where reg_number = card -> 'card' ->> 'reg_number';
  -- Location only with the scanner's consent, rounded to ~1 km.
  loc := case when p_location ? 'lat' and p_location ? 'lng' then jsonb_build_object('lat', round((p_location ->> 'lat')::numeric, 2),
    'lng', round((p_location ->> 'lng')::numeric, 2), 'city', p_location ->> 'city') when p_location ? 'city' then jsonb_build_object('city', p_location ->> 'city') end;
  insert into public.access_log (machine_id, viewer_type, via, ip_hash, approx_location, user_agent_family)
  values (m.id, 'public', case when p_code is not null then 'scan' else 'web' end::public.access_via, p_ip_hash, loc, left(p_user_agent_family, 40));
  if m.status = 'stolen' then
    ev := app.log_event('machine.stolen_scanned', m.id, m.owner_org_id, null, jsonb_build_object('location', loc, 'via', case when p_code is not null then 'scan' else 'web' end));
    perform app.notify_org(m.owner_org_id, 'machine.stolen_scanned',
      jsonb_build_object('machine_id', m.id, 'reg_number', m.reg_number, 'location', loc, 'at', app.iso_ts(now())), '/machines/' || m.id, 'critical');
    perform app.notify_org(f.raised_by_org_id, 'machine.stolen_scanned',
      jsonb_build_object('machine_id', m.id, 'reg_number', m.reg_number, 'location', loc, 'at', app.iso_ts(now())), '/machines/' || m.id, 'critical')
      from public.flags f where f.machine_id = m.id and f.status = 'active' and f.type = 'stolen' and f.raised_by_org_id <> m.owner_org_id;
    perform app.enqueue_webhook(m.owner_org_id, 'machine.scanned', m.id, jsonb_build_object('location', loc), ev.id);
    perform app.enqueue_webhook(e.holder_org_id, 'machine.scanned', m.id, jsonb_build_object('location', loc), ev.id)
      from public.encumbrances e where e.machine_id = m.id and e.status = 'active';
  end if;
  return card;
end $$;

-- "Jag har sett maskinen" on the red page: a sighting with consented location and optional contact (SPEC §5.3).
create or replace function public.report_sighting(p_code text, p_reg text, p_ip_hash text, p_location jsonb, p_message text default null,
  p_contact text default null)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare card jsonb; m public.machines;
begin
  if not app.rate_limit_hit('sighting:' || coalesce(p_ip_hash, 'none'), 5, interval '1 hour') then perform app.raise('RATE_LIMITED'); end if;
  card := public.public_machine_card(p_code, p_reg);
  if not (card ->> 'found')::boolean then perform app.raise('NOT_FOUND'); end if;
  select * into m from public.machines where reg_number = card -> 'card' ->> 'reg_number';
  if m.status <> 'stolen' then return jsonb_build_object('ok', true); end if;
  perform app.log_event('machine.sighting_reported', m.id, m.owner_org_id, null,
    jsonb_build_object('location', p_location, 'has_contact', p_contact is not null));
  perform app.notify_org(m.owner_org_id, 'machine.sighting_reported', jsonb_build_object('machine_id', m.id, 'reg_number', m.reg_number,
    'location', p_location, 'message', left(p_message, 1000), 'contact', left(p_contact, 200)), '/machines/' || m.id, 'critical');
  perform app.notify_org(f.raised_by_org_id, 'machine.sighting_reported', jsonb_build_object('machine_id', m.id, 'reg_number', m.reg_number,
    'location', p_location, 'message', left(p_message, 1000), 'contact', left(p_contact, 200)), '/machines/' || m.id, 'critical')
    from public.flags f where f.machine_id = m.id and f.status = 'active' and f.type = 'stolen' and f.raised_by_org_id <> m.owner_org_id;
  return jsonb_build_object('ok', true);
end $$;

-- Signed-in scan of a label: full role view + access log with via=scan.
create or replace function public.scan_label(p_org_id uuid, p_code text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare actor uuid := app.require_actor(p_org_id, 'readonly', false); l public.labels; v jsonb;
begin
  select * into l from public.labels where code = p_code;
  if l.id is null or l.machine_id is null then return jsonb_build_object('found', false); end if;
  perform app.after_lookup(actor, array[l.machine_id], 'scan');
  v := app.machine_view(l.machine_id, actor);
  if v is null then return jsonb_build_object('found', false); end if;
  return jsonb_build_object('found', true, 'label_status', l.status, 'machine', v);
end $$;

create or replace function public.list_access_log(p_org_id uuid, p_machine_id uuid, p_limit int default 200)
returns jsonb language plpgsql stable security definer set search_path = '' as $$
declare actor uuid := app.require_actor(p_org_id, 'readonly', false); rel text[] := app.machine_relations(p_machine_id, array[actor]);
  full_log boolean := app.is_operator() or app.has_org_type(actor, 'authority');
begin
  if not (rel && array['owner', 'user'] or full_log) then perform app.raise('FORBIDDEN'); end if;
  return coalesce((select jsonb_agg(jsonb_build_object('id', a.id, 'viewer_type', a.viewer_type, 'via', a.via, 'created_at', a.created_at,
      'viewer_org_name', case when a.viewer_type in ('public', 'api') and a.viewer_org_id is null then null
        else (select name from public.organizations where id = a.viewer_org_id) end,
      'approx_location', a.approx_location, 'user_agent_family', a.user_agent_family,
      'ip_hash', case when full_log then a.ip_hash end) order by a.created_at desc)
    from (select * from public.access_log where machine_id = p_machine_id and (full_log or visible_to_owner)
          order by created_at desc limit least(greatest(p_limit, 1), 1000)) a), '[]'::jsonb);
end $$;

-- ---------- Documents RPC ----------
-- Who may read a document (SPEC §11.2 documents row).
create or replace function app.can_read_document(d public.documents)
returns boolean language plpgsql stable security definer set search_path = '' as $$
declare rel text[];
begin
  if d.id is null or d.status not in ('clean', 'scanning') then return false; end if;
  if d.org_id = any (app.current_org_ids()) or app.is_operator() or app.acts_as('authority') then return true; end if;
  if d.machine_id is null then return false; end if;
  if d.visibility = 'public' then return true; end if;
  rel := app.machine_relations(d.machine_id);
  if rel && array['owner', 'user'] then
    -- Documents follow the machine to the new owner unless the uploader kept them private (visibility owner and not
    -- chosen to follow at transfer).
    return d.visibility <> 'owner' or d.org_id = any (app.current_org_ids())
      or exists (select 1 from public.transfers t where t.machine_id = d.machine_id and t.status = 'completed'
                 and d.id = any (t.document_ids) and t.to_org_id = any (app.current_org_ids()))
      or not exists (select 1 from public.transfers t where t.machine_id = d.machine_id and t.status = 'completed' and t.completed_at > d.created_at);
  end if;
  if 'holder' = any (rel) and d.visibility in ('owner_and_financier', 'verifiers') then return true; end if;
  if 'inspector_assigned' = any (rel) and d.visibility = 'verifiers' then return true; end if;
  return false;
end $$;


-- Creates the monthly partitions for the current and next p_months months (run by the jobs runner).
create or replace function app.ensure_monthly_partitions(p_table text, p_months int default 3)
returns int language plpgsql security definer set search_path = '' as $$
declare i int; start_ date; end_ date; name_ text; n int := 0;
begin
  for i in 0..p_months loop
    start_ := (date_trunc('month', now()) + make_interval(months => i))::date;
    end_ := (start_ + interval '1 month')::date;
    name_ := p_table || '_' || to_char(start_, 'YYYYMM');
    if to_regclass('public.' || name_) is null then
      -- Rows already in the default partition for that range must move first.
      execute format('create table public.%I (like public.%I including defaults)', name_ || '_tmp', p_table);
      execute format('with moved as (delete from public.%I where created_at >= %L and created_at < %L returning *) insert into public.%I select * from moved',
        p_table || '_default', start_, end_, name_ || '_tmp');
      execute format('alter table public.%I attach partition public.%I for values from (%L) to (%L)', p_table, name_ || '_tmp', start_, end_);
      execute format('alter table public.%I rename to %I', name_ || '_tmp', name_);
      -- Partitions are tables of their own: without RLS a direct select would bypass the parent's policies.
      execute format('alter table public.%I enable row level security', name_);
      execute format('revoke all on public.%I from public, anon, authenticated', name_);
      n := n + 1;
    end if;
  end loop;
  return n;
end $$;
select app.ensure_monthly_partitions('access_log', 2);


$$;

create or replace function public.create_document_upload(p_org_id uuid, p_machine_id uuid, p_type public.document_type, p_filename text,
  p_mime text, p_size_bytes bigint, p_sha256 text, p_visibility public.document_visibility default 'owner')
returns jsonb language plpgsql security definer set search_path = '' as $$
declare actor uuid := app.require_actor(p_org_id); d public.documents; rel text[]; fname text;
begin
  if p_machine_id is not null then
    rel := app.machine_relations(p_machine_id, array[actor]);
    if not (rel && array['owner', 'user', 'registered_by', 'draft_owner', 'holder', 'inspector_assigned', 'transfer_party', 'operator']
            or app.has_org_type(actor, 'inspector') or app.has_org_type(actor, 'dealer')) then
      perform app.raise('FORBIDDEN');
    end if;
  end if;
  if p_mime not in ('application/pdf', 'image/jpeg', 'image/png', 'image/heic') then perform app.raise('VALIDATION', '{"field":"mime"}'); end if;
  if p_size_bytes is null or p_size_bytes < 1 or p_size_bytes > 26214400 then perform app.raise('VALIDATION', '{"field":"size","max":26214400}'); end if;
  if p_sha256 !~ '^[0-9a-f]{64}$' then perform app.raise('VALIDATION', '{"field":"sha256"}'); end if;
  fname := left(regexp_replace(coalesce(p_filename, 'file'), '[^A-Za-z0-9._-]+', '_', 'g'), 120);
  insert into public.documents (machine_id, org_id, type, storage_path, filename, mime, size_bytes, sha256, uploaded_by_user_id, visibility)
  values (p_machine_id, actor, p_type, actor || '/' || gen_random_uuid() || '/' || fname, fname, p_mime, p_size_bytes, p_sha256, auth.uid(), p_visibility)
  returning * into d;
  return jsonb_build_object('id', d.id, 'bucket', 'documents', 'path', d.storage_path);
end $$;

-- After the upload: the event carries the sha256 (SPEC §11.5). av-scan then marks the file clean/infected.
create or replace function public.finalize_document(p_org_id uuid, p_document_id uuid)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare actor uuid := app.require_actor(p_org_id); d public.documents; owner_org uuid;
begin
  select * into d from public.documents where id = p_document_id and org_id = actor and status = 'pending_upload' for update;
  if d.id is null then perform app.raise('NOT_FOUND'); end if;
  if to_regclass('storage.objects') is not null and not app.is_demo_mode() then
    if not exists (select 1 from storage.objects o where o.bucket_id = 'documents' and o.name = d.storage_path) then
      perform app.raise('UPLOAD_MISSING');
    end if;
  end if;
  update public.documents set status = case when app.is_demo_mode() then 'clean' else 'scanning' end,
    exif_stripped = d.mime not in ('image/jpeg', 'image/heic') or app.is_demo_mode()
  where id = d.id returning * into d;
  select owner_org_id into owner_org from public.machines where id = d.machine_id;
  perform app.log_event('document.uploaded', d.machine_id, coalesce(owner_org, actor), actor,
    jsonb_build_object('document_id', d.id, 'type', d.type, 'sha256', d.sha256, 'size_bytes', d.size_bytes, 'visibility', d.visibility));
  return app.document_json(d);
end $$;

-- Result from Edge Function av-scan (service role).
create or replace function public.record_document_scan(p_document_id uuid, p_clean boolean, p_exif_stripped boolean, p_sha256_after text default null)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare d public.documents;
begin
  update public.documents set status = case when p_clean then 'clean' else 'infected' end, exif_stripped = p_exif_stripped
  where id = p_document_id returning * into d;
  if d.id is null then perform app.raise('NOT_FOUND'); end if;
  if not p_clean then
    perform app.log_event('document.quarantined', d.machine_id, d.org_id, null, jsonb_build_object('document_id', d.id));
    perform app.notify_org(d.org_id, 'document.infected', jsonb_build_object('filename', d.filename), '/machines/' || d.machine_id, 'warning');
  elsif p_sha256_after is not null and p_sha256_after <> d.sha256 then
    perform app.log_event('document.sanitized', d.machine_id, d.org_id, null,
      jsonb_build_object('document_id', d.id, 'sha256_original', d.sha256, 'sha256_stored', p_sha256_after));
  end if;
  return app.document_json(d);
end $$;

create or replace function public.list_documents(p_org_id uuid, p_machine_id uuid)
returns jsonb language plpgsql stable security definer set search_path = '' as $$
declare actor uuid := app.require_actor(p_org_id, 'readonly', false);
begin
  return coalesce((select jsonb_agg(app.document_json(d) order by d.created_at desc) from public.documents d
    where d.machine_id = p_machine_id and d.archived_at is null and app.can_read_document(d)), '[]'::jsonb);
end $$;

-- Authorises a download; Edge Function document-url then signs a 5-minute URL.
create or replace function public.authorize_document_download(p_document_id uuid, p_share_token text default null)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare d public.documents; s public.share_links;
begin
  select * into d from public.documents where id = p_document_id and archived_at is null;
  if d.id is null then perform app.raise('NOT_FOUND'); end if;
  if p_share_token is not null then
    select * into s from public.share_links where token_hash = app.sha256_hex(p_share_token) and revoked_at is null and expires_at > now();
    if s.id is null or s.machine_id is distinct from d.machine_id or d.visibility not in ('verifiers', 'public') or d.status <> 'clean' then
      perform app.raise('NOT_FOUND');
    end if;
  elsif not app.can_read_document(d) or d.status <> 'clean' then
    perform app.raise('NOT_FOUND');
  end if;
  if d.machine_id is not null then
    perform app.after_lookup((select x from unnest(app.current_org_ids()) x limit 1), array[d.machine_id], case when p_share_token is null then 'web' else 'share_link' end);
  end if;
  return jsonb_build_object('bucket', 'documents', 'path', d.storage_path, 'filename', d.filename, 'mime', d.mime, 'expires_in', 300);
end $$;

create or replace function public.set_document_visibility(p_org_id uuid, p_document_id uuid, p_visibility public.document_visibility)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare actor uuid := app.require_actor(p_org_id); d public.documents;
begin
  select * into d from public.documents where id = p_document_id for update;
  if d.id is null then perform app.raise('NOT_FOUND'); end if;
  if (d.org_id = actor or (select owner_org_id from public.machines where id = d.machine_id) = actor) is not true then perform app.raise('FORBIDDEN'); end if;
  if d.type in ('police_report', 'financing_contract') and p_visibility = 'public' then perform app.raise('VALIDATION', '{"field":"visibility"}'); end if;
  update public.documents set visibility = p_visibility where id = d.id returning * into d;
  perform app.log_event('document.visibility_changed', d.machine_id, d.org_id, actor, jsonb_build_object('document_id', d.id, 'visibility', p_visibility));
  return app.document_json(d);
end $$;

create or replace function public.archive_document(p_org_id uuid, p_document_id uuid)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare actor uuid := app.require_actor(p_org_id); d public.documents;
begin
  update public.documents set archived_at = now() where id = p_document_id and org_id = actor and archived_at is null and not generated
  returning * into d;
  if d.id is null then perform app.raise('NOT_FOUND'); end if;
  perform app.log_event('document.archived', d.machine_id, d.org_id, actor, jsonb_build_object('document_id', d.id, 'sha256', d.sha256));
  return jsonb_build_object('ok', true);
end $$;

-- Primary photo: a clean, public photo_machine document; av-scan copies it to the public machine-photos bucket.
create or replace function public.set_primary_photo(p_org_id uuid, p_machine_id uuid, p_document_id uuid)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare actor uuid := app.require_actor(p_org_id); d public.documents; m public.machines;
begin
  select * into m from public.machines where id = p_machine_id;
  if (m.owner_org_id = actor or m.registered_by_org_id = actor and m.status = 'draft') is not true then perform app.raise('FORBIDDEN'); end if;
  select * into d from public.documents where id = p_document_id and machine_id = p_machine_id;
  if d.id is null or d.type <> 'photo_machine' or d.mime not in ('image/jpeg', 'image/png') then perform app.raise('VALIDATION', '{"field":"document"}'); end if;
  update public.documents set visibility = 'public' where id = d.id;
  update public.machines set primary_photo_path = m.id || '/' || d.id || case when d.mime = 'image/png' then '.png' else '.jpg' end where id = m.id;
  perform app.log_event('machine.photo_set', m.id, m.owner_org_id, actor, jsonb_build_object('document_id', d.id, 'sha256', d.sha256));
  return jsonb_build_object('ok', true, 'primary_photo_path', m.id || '/' || d.id || case when d.mime = 'image/png' then '.png' else '.jpg' end,
    'source_path', d.storage_path);
end $$;

-- ---------- Share links (SPEC §6.10) ----------
create or replace function public.create_share_link(p_org_id uuid, p_machine_id uuid, p_scope public.share_scope default 'buyer_report',
  p_days int default 7, p_max_views int default null, p_params jsonb default '{}'::jsonb)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare actor uuid := app.require_actor(p_org_id); token text := encode(extensions.gen_random_bytes(24), 'hex'); s public.share_links;
begin
  if p_days not in (1, 7, 30, 90) then perform app.raise('VALIDATION', '{"field":"days"}'); end if;
  if p_scope in ('public_card', 'buyer_report') then
    if p_machine_id is null or (select owner_org_id from public.machines where id = p_machine_id) is distinct from actor then
      perform app.raise('FORBIDDEN');
    end if;
  elsif p_machine_id is not null then
    perform app.raise('VALIDATION', '{"field":"machine_id"}');
  end if;
  insert into public.share_links (machine_id, org_id, created_by_user_id, token_hash, token_prefix, scope, params, expires_at, max_views)
  values (p_machine_id, actor, auth.uid(), app.sha256_hex(token), left(token, 8), p_scope, coalesce(p_params, '{}'),
          now() + make_interval(days => p_days), p_max_views)
  returning * into s;
  perform app.log_event('share_link.created', p_machine_id, actor, actor,
    jsonb_build_object('share_link_id', s.id, 'scope', p_scope, 'expires_at', s.expires_at, 'max_views', p_max_views));
  return jsonb_build_object('id', s.id, 'token', token, 'expires_at', s.expires_at, 'scope', s.scope, 'max_views', s.max_views);
end $$;

create or replace function public.list_share_links(p_org_id uuid, p_machine_id uuid default null)
returns jsonb language plpgsql stable security definer set search_path = '' as $$
declare actor uuid := app.require_actor(p_org_id, 'readonly', false);
begin
  return coalesce((select jsonb_agg(jsonb_build_object('id', s.id, 'machine_id', s.machine_id, 'scope', s.scope, 'token_prefix', s.token_prefix,
      'expires_at', s.expires_at, 'max_views', s.max_views, 'views', s.views, 'revoked_at', s.revoked_at, 'created_at', s.created_at,
      'active', s.revoked_at is null and s.expires_at > now() and (s.max_views is null or s.views < s.max_views)) order by s.created_at desc)
    from public.share_links s where s.org_id = actor and (p_machine_id is null or s.machine_id = p_machine_id)), '[]'::jsonb);
end $$;

create or replace function public.revoke_share_link(p_org_id uuid, p_share_link_id uuid)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare actor uuid := app.require_actor(p_org_id); s public.share_links;
begin
  update public.share_links set revoked_at = now() where id = p_share_link_id and org_id = actor and revoked_at is null returning * into s;
  if s.id is null then perform app.raise('NOT_FOUND'); end if;
  perform app.log_event('share_link.revoked', s.machine_id, actor, actor, jsonb_build_object('share_link_id', s.id));
  return jsonb_build_object('ok', true);
end $$;


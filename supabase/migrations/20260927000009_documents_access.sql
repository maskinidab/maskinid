-- ---------- Documents ----------
create table public.documents (
  id                  uuid primary key default gen_random_uuid(),
  machine_id          uuid references public.machines (id),
  org_id              uuid not null references public.organizations (id),
  type                public.document_type not null,
  storage_path        text not null unique,
  filename            text not null,
  mime                text not null check (mime in ('application/pdf', 'image/jpeg', 'image/png', 'image/heic')),
  size_bytes          bigint not null check (size_bytes between 1 and 26214400),  -- max 25 MB
  sha256              text not null check (sha256 ~ '^[0-9a-f]{64}$'),
  uploaded_by_user_id uuid,
  visibility          public.document_visibility not null default 'owner',
  status              text not null default 'pending_upload' check (status in ('pending_upload', 'scanning', 'clean', 'infected', 'failed')),
  exif_stripped       boolean not null default false,
  gps_consent_location jsonb,                -- only with explicit consent (theft scans), never from EXIF
  generated           boolean not null default false,   -- PDFs generated by the system (certificates, receipts, reports)
  archived_at         timestamptz,
  created_at          timestamptz not null default now()
);
create index documents_machine_idx on public.documents (machine_id, created_at desc);
create index documents_org_idx on public.documents (org_id);

-- Storage buckets: private documents (signed URLs, 5 min, issued by Edge Function document-url) and public machine
-- photos (only the primary photo, EXIF stripped, copied there by av-scan).
do $$ begin
  if to_regclass('storage.buckets') is not null then
    insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
    values ('documents', 'documents', false, 26214400, array['application/pdf', 'image/jpeg', 'image/png', 'image/heic'])
    on conflict (id) do update set public = false, file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;
    insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
    values ('machine-photos', 'machine-photos', true, 5242880, array['image/jpeg', 'image/png'])
    on conflict (id) do update set public = true;
  end if;
end $$;

-- Uploads go straight to storage, but only to a path reserved by create_document_upload for this user.
create or replace function app.can_upload_document(p_path text)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.documents d where d.storage_path = p_path
    and d.uploaded_by_user_id = auth.uid() and d.status = 'pending_upload')
$$;
grant execute on function app.can_upload_document(text) to authenticated;
do $$ begin
  if to_regclass('storage.objects') is not null then
    execute $p$
      create policy documents_upload_reserved on storage.objects for insert to authenticated with check (
        bucket_id = 'documents' and app.can_upload_document(name))
    $p$;
  end if;
end $$;

